"""Generate the new authoring envelopes from the actual FastAPI OpenAPI schema."""

from __future__ import annotations

import json
from pathlib import Path

from app.main import app

REFERENCES = {
    "LayoutDefinition-Input": "LayoutDefinition",
    "LayoutDefinition-Output": "LayoutDefinition",
    "DocumentIdentityConfig": "DocumentIdentity",
    "DocumentNameConfig": "DocumentNameRule",
    "FieldMappingsResponse": "FieldMappingsResponse",
}


def typescript(schema: dict) -> str:
    if "$ref" in schema:
        return REFERENCES[schema["$ref"].rsplit("/", 1)[-1]]
    if "anyOf" in schema:
        return " | ".join(typescript(item) for item in schema["anyOf"])
    if "enum" in schema:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in schema["enum"])
    match schema.get("type"):
        case "string":
            return "string"
        case "integer" | "number":
            return "number"
        case "boolean":
            return "boolean"
        case "null":
            return "null"
        case "array":
            return f"Array<{typescript(schema['items'])}>"
        case "object":
            return "Record<string, unknown>"
        case _:
            raise ValueError(f"Unsupported schema: {schema}")


def main() -> None:
    schemas = app.openapi()["components"]["schemas"]
    source = "// Generated by backend/scripts/generate_authoring_types.py. Do not edit.\n"
    source += (
        'import type { LayoutDefinition, DocumentIdentity, DocumentNameRule, '
        'FieldMappingsResponse } from "../types";\n\n'
    )
    for name in ("TemplateAuthoringUpdate", "TemplateAuthoringView"):
        schema = schemas[name]
        source += f"export type {name} = {{\n"
        for key, value in schema["properties"].items():
            optional = "" if key in schema.get("required", []) else "?"
            source += f"  {key}{optional}: {typescript(value)};\n"
        source += "};\n\n"
    root = Path(__file__).resolve().parents[2]
    (root / "frontend/src/assistant/generatedAuthoring.ts").write_text(
        source, encoding="utf-8", newline="\n"
    )


if __name__ == "__main__":
    main()
