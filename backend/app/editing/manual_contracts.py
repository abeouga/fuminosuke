"""Trusted editor transport. These types are never included in model tools."""

from typing import Annotated, Literal

from pydantic import Field

from app.editing.contracts import BatchResult, ContextResult, Contract, EditingProblem
from app.editing.manual_draft import (
    ManualDraft as ManualDraft,
)
from app.editing.manual_draft import (
    ManualOcrDraft as ManualOcrDraft,
)


class ManualEdit(Contract):
    contract_version: Literal["editing.v1"]
    request_id: Annotated[str, Field(pattern=r"^[A-Za-z0-9_-]{1,128}$", strict=True)]
    expected_revision: int = Field(ge=1, strict=True)
    context_revision: int = Field(ge=1, strict=True)
    local_edit_epoch: int = Field(ge=0, strict=True)
    origin: Literal["manual"]
    turn_id: None
    draft: ManualDraft


class ManualView(Contract):
    context: ContextResult
    draft: ManualDraft


class ManualResult(BatchResult):
    # Only identity substitutions generated by this successful request. Never a rebase
    # against another writer's revision. Paths remain private to the hand editor.
    substitutions: dict[str, str] = Field(default_factory=dict)


class ManualReceipt(Contract):
    request_id: str
    state: Literal["NOT_FOUND", "PENDING", "SUCCEEDED", "FAILED"]
    result: ManualResult | None
    error: EditingProblem | None


class ManualOcrEdit(Contract):
    contract_version: Literal["editing.v1"]
    request_id: Annotated[str, Field(pattern=r"^[A-Za-z0-9_-]{1,128}$", strict=True)]
    expected_revision: int = Field(ge=1, strict=True)
    context_revision: int = Field(ge=1, strict=True)
    local_edit_epoch: int = Field(ge=0, strict=True)
    origin: Literal["manual"]
    turn_id: None
    draft: ManualOcrDraft
