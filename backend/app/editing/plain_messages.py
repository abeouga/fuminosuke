# Internal words a person cannot act on; a message still carrying one is replaced.
JARGON = re.compile(
    r"session|turn|context|revision|digest|cursor|localRef|requestId|eventId|handle|\bmode\b"
    r"|DRAFT|ACTIVE|\bDB\b|\bID\b|\bAPI\b|schema|mapping|snapshot"
    r"|世代|物理|操作群|選択肢群|矩形|依存|一意|正本|由来|所有者|単一値|識別子|不正です"
)

_BY_KIND = (
    (("EXPIRED",), EXPIRED),
    (("STALE", "REVISION", "SESSION", "CONTEXT", "RESOURCE", "IDEMPOTENCY", "CURSOR"), RELOAD),
    (("VOICE", "TURN", "QUESTION", "CONTINUATION"), VOICE),
    (("PLANNER",), AI_UNREADABLE),
)


def plain(code: str, message: str) -> str:
    """The message shown to people for a refusal with ``code``."""
    text = PLAIN.get(message, message)
    if not JARGON.search(text):
        return text
    return next((m for keys, m in _BY_KIND if any(k in code for k in keys)), RETRY)
